cask "vscode" do
  version "1.139.1"
  sha256 "b769b3980d4e2a38dc27d11278450087f6fec858fcd0a88d0643fa2fbb7f32f9"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/vscode-v#{version}/vscode-#{version}-x86_64.AppImage"
  name "Visual Studio Code"
  desc "Repackage of Visual Studio Code as an AppImage"
  homepage "https://code.visualstudio.com/"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^vscode-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  conflicts_with cask: ["visual-studio-code", "vscodium"]
  depends_on arch: :x86_64
  depends_on :linux

  app_image "vscode-#{version}-x86_64.AppImage", target: "vscode-x86_64.AppImage"
  binary "vscode-#{version}-x86_64.AppImage", target: "code"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/code", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/vscode.png",
         ".local/share/icons/hicolor/256x256/apps/vscode.png",
         target_base: :home
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file ".local/share/applications/vscode.desktop", <<~EOS, base: :home
      # generated by brew cask install steps
      [Desktop Entry]
      Name=Visual Studio Code
      Comment=Code Editing. Redefined.
      Exec="{{HOMEBREW_PREFIX}}/bin/code" %F
      Icon=vscode
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      StartupWMClass=Code
      MimeType=application/x-code-workspace;
    EOS
  end

  zap trash: [
    "~/.cache/Code",
    "~/.config/Code",
    "~/.local/share/applications/vscode.desktop",
    "~/.local/share/icons/hicolor/256x256/apps/vscode.png",
    "~/.vscode",
    "~/.vscode-cli",
    "~/.vscode-server",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force vscode
  EOS
end
