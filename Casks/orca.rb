cask "orca" do
  version "1.4.271"
  sha256 "91abe853907b6b36e1f618cbeba420f61eaa4b973eef329de3c763672e046306"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/orca-v#{version}/orca-#{version}-x86_64.AppImage"
  name "Orca"
  desc "Next-gen IDE for parallel agentic development"
  homepage "https://github.com/stablyai/orca"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^orca-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  depends_on arch: :x86_64
  depends_on :linux

  app_image "orca-#{version}-x86_64.AppImage", target: "orca-x86_64.AppImage"
  binary "orca-#{version}-x86_64.AppImage", target: "orca-ide"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/orca-ide", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/orca.png",
         ".local/share/icons/hicolor/512x512/apps/orca-ide.png",
         target_base: :home
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file ".local/share/applications/orca-ide.desktop", <<~EOS, base: :home
      # generated by brew cask install steps
      [Desktop Entry]
      Name=Orca IDE
      Comment=Next-gen IDE for parallel agentic development
      Exec="{{HOMEBREW_PREFIX}}/bin/orca-ide" %U
      Icon=orca-ide
      Terminal=false
      Type=Application
      StartupNotify=true
      StartupWMClass=orca
      Categories=Utility;
      MimeType=text/markdown;text/csv;text/tab-separated-values;x-scheme-handler/orca;
    EOS
  end

  zap trash: [
    "~/.cache/orca",
    "~/.config/orca",
    "~/.local/bin/orca",
    "~/.local/share/applications/orca-ide.desktop",
    "~/.local/share/icons/hicolor/512x512/apps/orca-ide.png",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force orca
  EOS
end
