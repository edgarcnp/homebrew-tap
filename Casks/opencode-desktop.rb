cask "opencode-desktop" do
  arch arm: "aarch64", intel: "x86_64"

  version "1.18.23"
  sha256 arm64_linux:  "65192e756356458c34de3f1143b4a3a5581beb2a09e4595e85a9cb21e1fb7ba6",
         x86_64_linux: "4f3decfbf8d4574474052f1b61319db7c8f195c9c5ee3962dfa3049a5b8da1ba"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/opencode-desktop-v#{version}/opencode-desktop-#{version}-#{arch}.AppImage",
      verified: "github.com/edgarcnp/homebrew-tap/"
  name "OpenCode Desktop"
  desc "Open source AI coding agent"
  homepage "https://opencode.ai/"

  livecheck do
    url "https://api.github.com/repos/edgarcnp/homebrew-tap/releases?per_page=100"
    strategy :json do |json|
      versions = json.filter_map do |release|
        next if release["draft"] || release["prerelease"]

        tag = release["tag_name"]
        next unless tag&.start_with?("opencode-desktop-v")

        candidate = tag.delete_prefix("opencode-desktop-v")
        next if candidate.empty?

        candidate
      end
      versions.max_by { |candidate| Gem::Version.new(candidate) }
    end
  end

  conflicts_with cask: "opencode-desktop"
  depends_on :linux

  app_image "opencode-desktop-#{version}-#{arch}.AppImage"
  binary "opencode-desktop-#{version}-#{arch}.AppImage", target: "opencode-desktop"
  artifact "opencode-desktop.desktop", target: "#{Dir.home}/.local/share/applications/opencode-desktop.desktop"

  preflight do
    FileUtils.chmod "+x", staged_path/"opencode-desktop-#{version}-#{arch}.AppImage"
    system(staged_path/"opencode-desktop-#{version}-#{arch}.AppImage", "--appimage-extract",
           chdir: staged_path) || odie("AppImage extraction failed")

    icon_dir = "#{Dir.home}/.local/share/icons/hicolor/128x128/apps" # 128x128 per upstream build-appimage.sh:58-59
    applications_dir = "#{Dir.home}/.local/share/applications"
    FileUtils.mkdir_p [icon_dir, applications_dir]

    icon_source = staged_path/"squashfs-root/opencode-desktop.png"
    odie "Icon source not found: #{icon_source}" unless icon_source.exist?

    FileUtils.cp icon_source, "#{icon_dir}/opencode-desktop.png"
    FileUtils.rm_r(staged_path/"squashfs-root", secure: true)

    File.write(staged_path/"opencode-desktop.desktop", <<~EOS)
      # generated by cask preflight
      [Desktop Entry]
      Name=OpenCode
      Comment=Open source AI coding agent
      Exec="#{HOMEBREW_PREFIX}/bin/opencode-desktop" %U
      Icon=opencode-desktop
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      MimeType=x-scheme-handler/opencode;
      StartupWMClass=ai.opencode.desktop
    EOS
  end

  zap trash: [
    "~/.cache/ai.opencode.desktop",
    "~/.config/ai.opencode.desktop",
    "~/.local/share/ai.opencode.desktop",
    "~/.local/share/applications/opencode-desktop.desktop",
    "~/.local/share/icons/hicolor/128x128/apps",
    "~/.local/share/icons/hicolor/128x128/apps/opencode-desktop.png",
  ]

  caveats <<~EOS
    This AppImage requires libfuse2 and unprivileged user namespaces.
    On Fedora both are enabled by default. On Debian/Ubuntu install
    libfuse2 and ensure kernel.unprivileged_userns_clone=1.
  EOS
end
