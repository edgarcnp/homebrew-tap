cask "thinkrail" do
  version "0.4.0"
  sha256 "e8784b7d6b8bc129a217e04b484eacc0bdb982721af14c250c4dedfa4780858e"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/thinkrail-v#{version}/thinkrail-#{version}-x86_64.AppImage"
  name "ThinkRail"
  desc "Repackage of ThinkRail as an AppImage"
  homepage "https://github.com/JetBrains/thinkrail"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^thinkrail-v(\d+\.\d+\.\d+)$/)
    strategy :git
  end

  auto_updates false
  depends_on arch: :x86_64
  depends_on :linux

  app_image "thinkrail-#{version}-x86_64.AppImage", target: "thinkrail-x86_64.AppImage"
  binary "thinkrail-#{version}-x86_64.AppImage", target: "thinkrail"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/thinkrail", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/thinkrail.png",
         ".local/share/icons/hicolor/512x512/apps/thinkrail.png",
         target_base: :home
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file ".local/share/applications/thinkrail.desktop", <<~EOS, base: :home
      # generated by brew cask install steps
      [Desktop Entry]
      Name=ThinkRail
      Comment=The agentic IDE that gets better every time you use it
      GenericName=Agentic IDE
      Exec="{{HOMEBREW_PREFIX}}/bin/thinkrail"
      Icon=thinkrail
      Terminal=false
      Type=Application
      StartupNotify=true
      StartupWMClass=ThinkRail
      Categories=Development;IDE;
    EOS
  end

  zap trash: [
    "~/.cache/ai.thinkrail.app",
    "~/.local/share/ai.thinkrail.app",
    "~/.local/share/applications/thinkrail.desktop",
    "~/.local/share/icons/hicolor/512x512/apps/thinkrail.png",
    "~/.thinkrail",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force thinkrail

    ThinkRail keeps its projects, chats and logs in ~/.thinkrail, and writes the
    bundled pi agent's config into ~/.pi/agent. The zap stanza removes ~/.thinkrail
    only, because ~/.pi is shared with a pi you may have installed yourself.

    Upstream collects usage events and error reports by default. Pass --no-analytics
    or set THINKRAIL_NO_ANALYTICS=1 to turn the additional sharing off.
  EOS
end
