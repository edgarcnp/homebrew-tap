cask "opencode-desktop" do
  arch arm: "aarch64", intel: "x86_64"

  version "1.18.25"
  sha256 arm64_linux:  "b0ebfa68bd22c3ea5d1991ff85babc89265f1324aa311b6597e2ab4a6d2285fb",
         x86_64_linux: "a6b2439a6ed13747e880504fb795ef5efd69523aa834b276b5c6fdc153e32896"

  xdg_data_home = ENV.fetch("XDG_DATA_HOME", File.join(Dir.home, ".local", "share"))
  xdg_config_home = ENV.fetch("XDG_CONFIG_HOME", File.join(Dir.home, ".config"))
  xdg_cache_home = ENV.fetch("XDG_CACHE_HOME", File.join(Dir.home, ".cache"))

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/opencode-desktop-v#{version}/opencode-desktop-#{version}-#{arch}.AppImage",
      verified: "github.com/edgarcnp/homebrew-tap"
  name "OpenCode Desktop"
  desc "Open source AI coding agent"
  homepage "https://opencode.ai/"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^opencode-desktop-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  depends_on :linux

  app_image "opencode-desktop-#{version}-#{arch}.AppImage"
  binary "opencode-desktop-#{version}-#{arch}.AppImage", target: "opencode-desktop"

  preflight do
    FileUtils.chmod "+x", staged_path/"opencode-desktop-#{version}-#{arch}.AppImage"
    system(staged_path/"opencode-desktop-#{version}-#{arch}.AppImage", "--appimage-extract",
           chdir: staged_path) || odie("AppImage extraction failed")

    icon_dir = "#{xdg_data_home}/icons/hicolor/128x128/apps" # 128x128 per upstream build-appimage.sh:52-53,83-85
    applications_dir = "#{xdg_data_home}/applications"
    FileUtils.mkdir_p [icon_dir, applications_dir]

    icon_source = staged_path/"squashfs-root/opencode-desktop.png"
    odie "Icon source not found: #{icon_source}" unless icon_source.exist?

    FileUtils.cp icon_source, "#{icon_dir}/opencode-desktop.png"
    FileUtils.rm_r(staged_path/"squashfs-root")

    File.write("#{applications_dir}/opencode-desktop.desktop", <<~EOS)
      # generated by cask preflight
      [Desktop Entry]
      Name=OpenCode
      Comment=Open source AI coding agent
      Exec="#{HOMEBREW_PREFIX}/bin/opencode-desktop" %U
      Icon=opencode-desktop
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      MimeType=x-scheme-handler/opencode;
      StartupWMClass=ai.opencode.desktop
    EOS
  end

  uninstall trash: [
    "#{xdg_data_home}/applications/opencode-desktop.desktop",
    "#{xdg_data_home}/icons/hicolor/128x128/apps/opencode-desktop.png",
  ]

  zap trash: [
    "#{xdg_cache_home}/ai.opencode.desktop",
    "#{xdg_config_home}/ai.opencode.desktop",
    "#{xdg_data_home}/ai.opencode.desktop",
    "#{xdg_data_home}/applications/opencode-desktop.desktop",
    "#{xdg_data_home}/icons/hicolor/128x128/apps/opencode-desktop.png",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
  EOS
end
