cask "artcraft-launcher" do
  version "0.5.1"
  sha256 "8d689b10e546d632ef381965671549829b3a1fb5f4efa51dca97781567973d4c"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/artcraft-launcher-v#{version}/artcraft-launcher-#{version}-x86_64.AppImage"
  name "ArtCraft Launcher"
  desc "Install, update and launch the Craft App Suite"
  homepage "https://github.com/storytold/craft-launcher"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^artcraft-launcher-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  depends_on arch: :x86_64
  depends_on :linux

  app_image "artcraft-launcher-#{version}-x86_64.AppImage", target: "artcraft-launcher-x86_64.AppImage"
  binary "artcraft-launcher-#{version}-x86_64.AppImage", target: "artcraft-launcher"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/artcraft-launcher", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/artcraft-launcher.svg",
         ".local/share/icons/hicolor/scalable/apps/artcraft-launcher.svg",
         target_base: :home
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file ".local/share/applications/artcraft-launcher.desktop", <<~EOS, base: :home
      # generated by brew cask install steps
      [Desktop Entry]
      Name=ArtCraft Launcher
      Comment=Install, update and launch the Craft App Suite
      Exec="{{HOMEBREW_PREFIX}}/bin/artcraft-launcher"
      Icon=artcraft-launcher
      Terminal=false
      Type=Application
      StartupNotify=true
      StartupWMClass=artcraft-launcher
      Categories=Utility;PackageManager;
    EOS
  end

  zap trash: [
    "~/.cache/artcraft-launcher",
    "~/.local/share/ai.storyteller.artcraft-launcher",
    "~/.local/share/applications/artcraft-launcher.desktop",
    "~/.local/share/artcraft-launcher",
    "~/.local/share/icons/hicolor/scalable/apps/artcraft-launcher.svg",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force artcraft-launcher
  EOS
end
