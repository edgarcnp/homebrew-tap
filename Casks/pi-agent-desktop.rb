cask "pi-agent-desktop" do
  version "0.8.7"
  sha256 "ba6fab0635f1334e387d822044fd69adf589d19f531461b39edfbcd1eb5637e2"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/pi-agent-desktop-v#{version}/pi-agent-desktop-#{version}-x86_64.AppImage"
  name "Pi Agent Desktop"
  desc "Desktop UI for the pi coding agent"
  homepage "https://github.com/abcwyc/pi-agent-desktop"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^pi-agent-desktop-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  depends_on arch: :x86_64
  depends_on :linux

  app_image "pi-agent-desktop-#{version}-x86_64.AppImage", target: "pi-agent-desktop-x86_64.AppImage"
  binary "pi-agent-desktop-#{version}-x86_64.AppImage", target: "pi-agent-desktop"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/pi-agent-desktop", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/pi-agent-desktop.png",
         ".local/share/icons/hicolor/128x128/apps/pi-agent-desktop.png",
         target_base: :home
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file ".local/share/applications/pi-agent-desktop.desktop", <<~EOS, base: :home
      # generated by brew cask install steps
      [Desktop Entry]
      Name=Pi Agent
      Comment=Desktop UI for the pi coding agent
      Exec="{{HOMEBREW_PREFIX}}/bin/pi-agent-desktop" %U
      Icon=pi-agent-desktop
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      StartupWMClass=pi-agent-desktop
    EOS
  end

  zap trash: [
    "~/.cache/com.abcwyc.pi-agent",
    "~/.config/com.abcwyc.pi-agent",
    "~/.local/share/applications/pi-agent-desktop.desktop",
    "~/.local/share/com.abcwyc.pi-agent",
    "~/.local/share/icons/hicolor/128x128/apps/pi-agent-desktop.png",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force pi-agent-desktop

    Sessions, models and credentials live in ~/.pi and are shared with the pi CLI.
  EOS
end
