cask "vscode" do
  arch arm: "aarch64", intel: "x86_64"

  version "1.135.0"
  sha256 arm64_linux:  "6b8fe0ccdb73a347c70bbfc5e682eb757a1b97475abb2c7e898d113d4cc27b67",
         x86_64_linux: "fd4773133228ce03bfe4f5796374f45c03a9a3ffc5e66cd821ed8eca295a8004"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/vscode-v#{version}/vscode-#{version}-#{arch}.AppImage",
      verified: "github.com/edgarcnp/homebrew-tap"
  name "Visual Studio Code"
  desc "Repackage of Visual Studio Code as an AppImage"
  homepage "https://code.visualstudio.com/"

  livecheck do
    url "https://api.github.com/repos/edgarcnp/homebrew-tap/releases?per_page=100"
    strategy :json do |json|
      versions = json.filter_map do |release|
        next if release["draft"] || release["prerelease"]

        tag = release["tag_name"]
        next unless tag&.start_with?("vscode-v")

        candidate = tag.delete_prefix("vscode-v")
        next if candidate.empty?
        next unless candidate.match?(/\A\d+\.\d+\.\d+(?:[.-]\w+)*\z/)

        candidate
      end
      versions.max_by { |candidate| Gem::Version.new(candidate) }
    end
  end

  auto_updates false
  conflicts_with cask: ["visual-studio-code", "code", "vscodium"]
  depends_on :linux

  app_image "vscode-#{version}-#{arch}.AppImage"
  binary "vscode-#{version}-#{arch}.AppImage", target: "code"
  artifact "vscode.desktop", target: "#{Dir.home}/.local/share/applications/vscode.desktop"

  preflight do
    FileUtils.chmod "+x", staged_path/"vscode-#{version}-#{arch}.AppImage"
    system(staged_path/"vscode-#{version}-#{arch}.AppImage", "--appimage-extract",
           chdir: staged_path) || odie("AppImage extraction failed")

    icon_dir = "#{Dir.home}/.local/share/icons/hicolor/256x256/apps" # 256x256 per upstream build-appimage.sh
    applications_dir = "#{Dir.home}/.local/share/applications"
    FileUtils.mkdir_p [icon_dir, applications_dir]

    icon_source = staged_path/"squashfs-root/vscode.png"
    odie "Icon source not found: #{icon_source}" unless icon_source.exist?

    FileUtils.cp icon_source, "#{icon_dir}/vscode.png"
    FileUtils.rm_r(staged_path/"squashfs-root")

    File.write(staged_path/"vscode.desktop", <<~EOS)
      # generated by cask preflight
      [Desktop Entry]
      Name=Visual Studio Code
      Comment=Code Editing. Redefined.
      Exec="#{HOMEBREW_PREFIX}/bin/code" %F
      Icon=vscode
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      MimeType=application/x-code-workspace;
      StartupWMClass=Code
    EOS
  end

  uninstall delete: [
    "#{Dir.home}/.local/share/applications/vscode.desktop",
    "#{Dir.home}/.local/share/icons/hicolor/256x256/apps/vscode.png",
  ]

  zap trash: [
    "~/.cache/Code",
    "~/.config/Code",
    "~/.local/share/applications/vscode.desktop",
    "~/.local/share/icons/hicolor/256x256/apps/vscode.png",
    "~/.vscode",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
  EOS
end
