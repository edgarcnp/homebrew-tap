cask "gitbutler" do
  arch arm: "aarch64", intel: "x86_64"

  version "0.22.3"
  sha256 arm64_linux:  "f75a1568a2a4892cd3c3763d2865a2ece38bd7ca196f9efad06970896e7b6d11",
         x86_64_linux: "33b24802b60cb33abf88609579e9ff780717e098a4a55faeacb6eb739c92c5ec"

  url "https://github.com/edgarcnp/homebrew-tap/releases/download/gitbutler-v#{version}/gitbutler-#{version}-#{arch}.AppImage"
  name "GitButler"
  desc "Git, finally designed for humans"
  homepage "https://gitbutler.com/"

  livecheck do
    url "https://github.com/edgarcnp/homebrew-tap.git"
    regex(/^gitbutler-v(\d+\.\d+\.\d+(?:[.-]\w+)*)$/)
    strategy :git
  end

  auto_updates false
  depends_on :linux

  app_image "gitbutler-#{version}-#{arch}.AppImage", target: "gitbutler-#{arch}.AppImage"
  binary "gitbutler-#{version}-#{arch}.AppImage", target: "gitbutler-tauri"
  binary "gitbutler-#{version}-#{arch}.AppImage", target: "but"

  postflight_steps do
    run "{{HOMEBREW_PREFIX}}/bin/gitbutler-tauri", args: ["--appimage-extract"], chdir: "{{staged_path}}"
    copy "squashfs-root/gitbutler.png", "~/.local/share/icons/hicolor/128x128/apps/gitbutler.png"
    remove "{{staged_path}}/squashfs-root", recursive: true
    write_file "~/.local/share/applications/gitbutler.desktop", <<~EOS
      # generated by brew cask install steps
      [Desktop Entry]
      Name=GitButler
      Comment=Git, finally designed for humans
      Exec="{{HOMEBREW_PREFIX}}/bin/gitbutler-tauri" %U
      Icon=gitbutler
      Terminal=false
      Type=Application
      StartupNotify=true
      Categories=Development;
      StartupWMClass=gitbutler-tauri
      MimeType=x-scheme-handler/but;
    EOS
  end

  zap trash: [
    "~/.cache/gitbutler",
    "~/.config/com.gitbutler.app",
    "~/.config/gitbutler",
    "~/.local/share/applications/gitbutler.desktop",
    "~/.local/share/com.gitbutler.app",
    "~/.local/share/gitbutler",
    "~/.local/share/icons/hicolor/128x128/apps/gitbutler.png",
  ]

  caveats <<~EOS
    This cask installs an AppImage that requires unprivileged user namespaces or FUSE.
    On some systems you may need to enable unprivileged_userns_clone or install FUSE3.
    The desktop entry and icon are only removed by the zap stanza. If you uninstalled
    without --zap, clean them up with:
      brew uninstall --zap --force gitbutler
  EOS
end
